const LANG_KEY = "ali-site-lang";
let currentLang = "en";
try {
  const saved = localStorage.getItem(LANG_KEY);
  if (saved === "ar" || saved === "en") currentLang = saved;
} catch (e) { /* storage unavailable: stay in English */ }

function t(key, vars) {
  let s = (STRINGS[currentLang] && STRINGS[currentLang][key]) || STRINGS.en[key] || key;
  if (vars) {
    Object.keys(vars).forEach((k) => (s = s.replace("{" + k + "}", vars[k])));
  }
  return s;
}

